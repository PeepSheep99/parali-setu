"""Writes config.js from the environment, so no key or URL is ever committed.

    set MAPS_API_KEY=...            (PowerShell: $env:MAPS_API_KEY = "...")
    set API_BASE=https://parali-setu-api-....run.app
    python build_config.py          # writes config.js

MAPS_API_KEY and API_BASE may also sit in a file named .env.local in this
folder (one KEY=value per line); that file is git-ignored. The Maps key is a
browser key, so it is visible to anyone who opens the site: it is protected by
its restrictions (Maps JavaScript API only, our site's address only), not by
secrecy.
"""
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load_env_file() -> dict:
    out = {}
    path = HERE / ".env.local"
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, _, value = line.partition("=")
                out[key.strip()] = value.strip().strip('"')
    return out


def main() -> None:
    env = {**load_env_file(), **{k: v for k, v in os.environ.items() if k in ("MAPS_API_KEY", "API_BASE")}}
    missing = [k for k in ("MAPS_API_KEY", "API_BASE") if not env.get(k)]
    if missing:
        raise SystemExit(f"Set {' and '.join(missing)} in the environment or in .env.local first.")
    (HERE / "config.js").write_text(
        "// Generated by build_config.py from the environment; do not commit real values.\n"
        f"const API_BASE = {json.dumps(env['API_BASE'])};\n\n"
        "// Browser key for the Maps JavaScript API. It only works from our own site\n"
        "// (HTTP referrer restriction) and only for Maps JS.\n"
        f"const MAPS_API_KEY = {json.dumps(env['MAPS_API_KEY'])};\n",
        encoding="utf-8")
    print("wrote config.js")


if __name__ == "__main__":
    main()
